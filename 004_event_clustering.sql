-- Stage 5C: additive event clustering; preserves both existing article feeds.
CREATE TABLE IF NOT EXISTS public.news_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,
  representative_article_id BIGINT REFERENCES public.articles(id) ON DELETE SET NULL,
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.articles ADD COLUMN IF NOT EXISTS event_id BIGINT REFERENCES public.news_events(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_articles_event_id ON public.articles(event_id) WHERE event_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_events_type ON public.news_events(event_type);
-- Public-facing apps should use a restricted database role; no public RLS policies are added.
ALTER TABLE public.news_events ENABLE ROW LEVEL SECURITY;
CREATE OR REPLACE VIEW public.event_coverage_summary AS
SELECT e.id AS event_id, e.event_type, e.representative_article_id,
       COUNT(a.id)::integer AS article_count,
       COUNT(DISTINCT lower(trim(a.source))) FILTER (WHERE nullif(trim(a.source),'') IS NOT NULL)::integer AS publisher_count,
       MAX(a.importance_score) AS max_importance_score,
       MAX(a."timestamp") AS latest_article_timestamp
FROM public.news_events e
JOIN public.articles a ON a.event_id = e.id AND a.processing_status = 'completed'
GROUP BY e.id, e.event_type, e.representative_article_id;
