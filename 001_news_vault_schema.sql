-- Initial faithful migration of the uploaded SQLite news_vault.db.
-- Timestamp-like columns remain TEXT because the source has timezone-naive values.
CREATE TABLE IF NOT EXISTS public.articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT,
  source TEXT,
  raw_content TEXT,
  summary TEXT,
  country_code TEXT,
  "timestamp" TEXT,
  link_url TEXT,
  topic_tag TEXT,
  image_url TEXT,
  processing_status TEXT NOT NULL DEFAULT 'completed',
  attempt_count INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TEXT,
  last_error TEXT,
  processed_at TEXT,
  model_used TEXT
);
CREATE INDEX IF NOT EXISTS idx_articles_queue ON public.articles (processing_status, next_attempt_at, id);

CREATE TABLE IF NOT EXISTS public.paid_inference_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  charged_utc_date TEXT NOT NULL,
  article_id BIGINT NOT NULL REFERENCES public.articles(id),
  model TEXT NOT NULL,
  reserved_usd DOUBLE PRECISION NOT NULL,
  actual_usd DOUBLE PRECISION,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_paid_inference_day ON public.paid_inference_ledger (charged_utc_date);

-- Keep these backend tables unavailable through the public Supabase Data API.
ALTER TABLE public.articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.paid_inference_ledger ENABLE ROW LEVEL SECURITY;
-- No policies are created: browser/anon/authenticated API clients cannot read them.
-- Trusted server-side PostgreSQL connections still require appropriate database privileges.
